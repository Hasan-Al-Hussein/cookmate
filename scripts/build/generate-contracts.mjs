import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';
import {
  schema,
  strictAjvOptions,
  validationRoots,
} from '../../packages/contracts/schema/contract.schema.mjs';

const directory = new URL('../../packages/contracts/src/generated/', import.meta.url);
const check = process.argv.includes('--check');
const ajv = new Ajv({
  ...strictAjvOptions,
  code: { source: true, esm: true, lines: true },
  inlineRefs: false,
});
ajv.addSchema(schema);
const exports = Object.fromEntries(
  validationRoots.map((name) => [`validate${name}`, `${schema.$id}#/definitions/${name}`]),
);
let validators = standaloneCode(ajv, exports);
// Keep the generated validators compiler-free and platform-neutral. This is the
// only Ajv runtime helpers allowed; reject future imports rather than hide drift.
validators = validators.replaceAll(
  'require("ajv/dist/runtime/ucs2length").default',
  'unicodeLength',
);
validators = validators.replaceAll('require("ajv/dist/runtime/equal").default', 'equal');
if (/\brequire\s*\(|\bimport\s/.test(validators))
  throw new Error('Unexpected validator runtime dependency');
validators = `// Generated by npm run contracts:generate. Do not edit.\nimport { unicodeLength } from '../unicode.js';\nimport equal from 'fast-deep-equal';\n${validators}`;
const types = await compile(schema, 'CookMateContract', {
  bannerComment: '/* Generated from contract.schema.mjs. Do not edit. */',
  unknownAny: true,
  additionalProperties: false,
  unreachableDefinitions: true,
  maxItems: -1,
});
const declarations = `// Generated. No Ajv runtime dependency.\nimport type * as Types from './types.js';\nexport interface ValidationIssue { instancePath: string; schemaPath: string; keyword: string; params: Record<string, unknown>; message?: string }\nexport interface Validator<T> { (value: unknown): value is T; errors?: ValidationIssue[] | null }\n${validationRoots.map((name) => `export const validate${name}: Validator<Types.${name}>;`).join('\n')}\n`;
const manifest =
  JSON.stringify(
    {
      schemaVersion: 2,
      schemaSha256: createHash('sha256').update(JSON.stringify(schema)).digest('hex'),
      validatorBytes: Buffer.byteLength(validators),
      validatorGzipBytes: gzipSync(validators).length,
      runtimeImports: ['../unicode.js', 'fast-deep-equal'],
      validators: validationRoots,
    },
    null,
    2,
  ) + '\n';

await mkdir(directory, { recursive: true });
for (const [name, contents] of Object.entries({
  'validators.js': validators,
  'validators.d.ts': declarations,
  'types.ts': types,
  'manifest.json': manifest,
  'contract.schema.json': JSON.stringify(schema, null, 2) + '\n',
})) {
  const target = new URL(name, directory);
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== contents) throw new Error(`Generated contract drift: ${fileURLToPath(target)}`);
  } else {
    await writeFile(target, contents, 'utf8');
  }
}
console.log(
  `${check ? 'Checked' : 'Generated'} ${validationRoots.length} validators (${Buffer.byteLength(validators)} bytes; gzip ${gzipSync(validators).length}).`,
);
